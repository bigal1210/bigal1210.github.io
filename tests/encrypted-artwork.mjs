import assert from 'node:assert/strict';
import {webcrypto,createHash} from 'node:crypto';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync(new URL('../assets/encrypted-artwork.js',import.meta.url),'utf8').replace('export async function','async function');
const content=JSON.stringify({version:1,ciphertext:'encrypted-fixture'});
const sha256=createHash('sha256').update(content).digest('hex');
const storage=new Map();let requests=0;
const cache={async match(url){return storage.get(url)?.clone();},async put(url,response){storage.set(url,response);},async delete(url){storage.delete(url);}};
const context=vm.createContext({URL,Response,TextDecoder,Uint8Array,crypto:webcrypto,location:{href:'https://example.test/rambling-baseball.html'},caches:{open:async()=>cache},fetch:async()=>{requests++;return new Response(content);}});
vm.runInContext(source,context);
context.entry={file:'artwork/baseball-123.encrypted.json',sha256};
await vm.runInContext('fetchEncryptedArtwork(entry)',context);
assert.equal(requests,1);
await vm.runInContext('fetchEncryptedArtwork(entry)',context);
assert.equal(requests,1,'Revisiting an unchanged encrypted bundle must use persistent cache');
context.entry={...context.entry,file:'artwork/baseball-456.encrypted.json'};
await vm.runInContext('fetchEncryptedArtwork(entry)',context);assert.equal(requests,2,'New versions must download separately');
storage.set(new URL(context.entry.file,context.location.href).href,new Response('tampered'));
await assert.rejects(vm.runInContext('fetchEncryptedArtwork(entry)',context),/integrity/);
assert.equal(storage.has(new URL(context.entry.file,context.location.href).href),false,'Discard corrupt cached bytes');
context.caches.open=async()=>{throw new Error('Storage disabled');};
await vm.runInContext('fetchEncryptedArtwork(entry)',context);assert.equal(requests,3,'Blocked storage must still permit download');
context.fetch=async()=>new Response('',{status:503});
await assert.rejects(vm.runInContext('fetchEncryptedArtwork(entry)',context),/download/);
console.log('Passed: encrypted cache reuse, version invalidation, integrity, blocked storage, network failure.');
